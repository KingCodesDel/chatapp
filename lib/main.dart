/// How long the animated splash screen stays on screen at app launch.
const kSplashDuration = Duration(seconds: 7);

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await ThemeController.instance.load();
  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<ThemeMode>(
      valueListenable: ThemeController.instance.mode,
      builder: (context, mode, _) {
        return MaterialApp(
          title: 'ChatVibe',
          debugShowCheckedModeBanner: false,
          theme: AppTheme.light,
          darkTheme: AppTheme.dark,
          themeMode: mode,
          home: _LaunchGate(
            child: StreamBuilder(
              stream: AuthService().authStateChanges,
              builder: (context, snapshot) {
                if (snapshot.connectionState == ConnectionState.waiting) {
                  return const SplashScreen();
                }
                if (snapshot.hasData) {
                  // NotificationService().init(snapshot.data!.uid); // uncomment once on Blaze
                  return _PresenceGate(uid: snapshot.data!.uid, child: const HomeScreen());
                }
                return const LoginScreen();
              },
            ),
          ),
        );
      },
    );
  }
}

/// Keeps the animated splash on top for [kSplashDuration] while the real app
/// (sign-in check, first screen) loads underneath, then fades it away.
class _LaunchGate extends StatefulWidget {
  final Widget child;
  const _LaunchGate({required this.child});

  @override
  State<_LaunchGate> createState() => _LaunchGateState();
}

class _LaunchGateState extends State<_LaunchGate> {
  bool _showSplash = true;
  Timer? _timer;

  @override
  void initState() {
    super.initState();
    _timer = Timer(kSplashDuration, () {
      if (mounted) setState(() => _showSplash = false);
    });
  }

  @override
  void dispose() {
    _timer?.cancel();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Stack(
      fit: StackFit.expand,
      children: [
        widget.child,
        AnimatedSwitcher(
          duration: const Duration(milliseconds: 600),
          child: _showSplash ? const SplashScreen(key: ValueKey('splash'), duration: kSplashDuration) : const SizedBox.shrink(key: ValueKey('none')),
        ),
      ],
    );
  }
}

/// Starts/stops presence (online + last-seen) tracking around the logged-in
/// portion of the app.
class _PresenceGate extends StatefulWidget {
  final String uid;
  final Widget child;
  const _PresenceGate({required this.uid, required this.child});

  @override
  State<_PresenceGate> createState() => _PresenceGateState();
}

class _PresenceGateState extends State<_PresenceGate> {
  late final PresenceService _presence;

  @override
  void initState() {
    super.initState();
    _presence = PresenceService(FirestoreService());
    _presence.start(widget.uid);
  }

  @override
  void dispose() {
    _presence.stop();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => widget.child;
}
